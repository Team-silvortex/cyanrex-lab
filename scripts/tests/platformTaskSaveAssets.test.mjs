// Fixed ESM mirrors reuse the pure planner; these checks make no HTTP or saving claim.
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { copyFile, mkdir, mkdtemp, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import { stripTypeScriptTypes } from "node:module";
import { tmpdir } from "node:os";
import path from "node:path";
import test from "node:test";
import { fileURLToPath, pathToFileURL } from "node:url";
import { promisify } from "node:util";
import { artifactResponse, clone, taskResponse } from "../../frontend/tests/helpers/taskContentSaveFixtures.mjs";

const execute = promisify(execFile);
const root = fileURLToPath(new URL("../../", import.meta.url));
const generator = "scripts/generate-platform-task-save-assets.mjs";
const sourceDirectory = "frontend/src/features/tasks";
const outputDirectory = "engine/src/bin/cyanrex-platform/session_ui/task-save";
const names = ["taskContentSave", "taskSaveContract", "taskDraft", "taskPayloadLanguage"];
const read = relative => readFile(path.join(root, relative), "utf8");
const run = (directory, args = []) => execute(process.execPath, [path.join(directory, generator), ...args],
  { cwd: tmpdir(), encoding: "utf8" });
const sha256 = source => createHash("sha256").update(source).digest("hex");

async function isolated(t) {
  const directory = await mkdtemp(path.join(tmpdir(), "cyanrex-task-save-assets-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  await mkdir(path.join(directory, "scripts"));
  await mkdir(path.join(directory, sourceDirectory), { recursive: true });
  await copyFile(path.join(root, generator), path.join(directory, generator));
  for (const name of names) await copyFile(path.join(root, sourceDirectory, `${name}.ts`),
    path.join(directory, sourceDirectory, `${name}.ts`));
  return directory;
}

test("common dependency-free script suite rejects any checked-in Task-save asset drift", async () => {
  const result = await run(root, ["--check"]);
  assert.match(result.stdout, /4.*synchronized/);
  const gate = await read("scripts/quality-gate.sh");
  assert.match(gate, /node --test "\$PROJECT_ROOT"\/scripts\/tests\/\*\.test\.mjs/);
  assert.match(await read(".github/workflows/ci.yml"), /scripts\/quality-gate\.sh --format-only/);
});

test("four ESM assets only strip types and rewrite reviewed sibling imports", async () => {
  for (const name of names) {
    const sourcePath = `${sourceDirectory}/${name}.ts`, source = await read(sourcePath);
    const asset = await read(`${outputDirectory}/${name}.js`);
    const header = [
      `// Generated by ${generator}; do not edit directly.`,
      `// Source: ${sourcePath}`,
      `// Source SHA-256: ${sha256(source)}`,
      "",
    ].join("\n");
    assert.ok(asset.startsWith(header), name);
    const emitted = asset.slice(header.length);
    const unrewritten = emitted.replace(/(["'])\.\/(taskContentSave|taskSaveContract|taskDraft|taskPayloadLanguage)\.js\1/g,
      (_match, quote, dependency) => `${quote}./${dependency}${quote}`);
    const stripped = stripTypeScriptTypes(source, { mode: "strip" }).replace(/\r\n?/g, "\n").replace(/[ \t]+$/gm, "");
    assert.equal(unrewritten, stripped, name);
    assert.doesNotMatch(asset, /\r|[ \t]+$/m, name);
    assert.ok(asset.split("\n").length <= 600, name);
    for (const dependency of emitted.matchAll(/^import\b[^\n]*\bfrom\s+["']([^"']+)["']/gm)) {
      assert.ok(names.some(value => dependency[1] === `./${value}.js`), dependency[1]);
    }
    await import(pathToFileURL(path.join(root, outputDirectory, `${name}.js`)).href);
  }
  const source = await read(generator);
  assert.doesNotMatch(source, /process\.env|\b(?:fetch|https?|child_process|typescript|esbuild|rollup)\b/);
  for (const imported of source.matchAll(/^import\b[^\n]*\bfrom\s+["']([^"']+)["']/gm)) {
    assert.ok(imported[1].startsWith("node:"), imported[1]);
  }
});

test("generation and --check are deterministic from any working directory and checks never repair drift", async t => {
  const directory = await isolated(t), output = path.join(directory, outputDirectory);
  await assert.rejects(run(directory, ["--check"]), /Task-save assets are stale/);
  await assert.rejects(stat(output), { code: "ENOENT" });
  await run(directory);
  assert.deepEqual((await readdir(output)).sort(), names.map(name => `${name}.js`).sort());
  const original = await Promise.all(names.map(name => readFile(path.join(output, `${name}.js`), "utf8")));
  await run(directory);
  assert.deepEqual(await Promise.all(names.map(name => readFile(path.join(output, `${name}.js`), "utf8"))), original);
  await run(directory, ["--check"]);
  const alteredPath = path.join(output, "taskDraft.js"), altered = `${original[2]}\n// drift\n`;
  await writeFile(alteredPath, altered);
  await assert.rejects(run(directory, ["--check"]), /taskDraft\.js/);
  assert.equal(await readFile(alteredPath, "utf8"), altered);
  await run(directory);
  const sourcePath = path.join(directory, sourceDirectory, "taskDraft.ts");
  await writeFile(sourcePath, `${await readFile(sourcePath, "utf8")}\n// changed source\n`);
  await assert.rejects(run(directory, ["--check"]), /taskDraft\.js/);
  assert.equal(await readFile(alteredPath, "utf8"), original[2]);
  await run(directory);
  await run(directory, ["--check"]);
});

test("fixed CLI refuses unreviewed paths and dependencies before writing assets", async t => {
  const directory = await isolated(t), output = path.join(directory, outputDirectory);
  for (const args of [["--output", "elsewhere"], ["--source", "arbitrary.ts"], ["--check", "--check"]]) {
    await assert.rejects(run(directory, args), /Usage:/);
    await assert.rejects(stat(output), { code: "ENOENT" });
  }
  const sourcePath = path.join(directory, sourceDirectory, "taskPayloadLanguage.ts");
  const original = await readFile(sourcePath, "utf8");
  for (const addition of [
    '\nimport { readFile } from "node:fs";\n',
    '\nimport { extra } from "./unreviewed";\n',
    '\nconst first = 1; import { extra } from "./unreviewed";\n',
    '\nimport {\n extra\n} from "./unreviewed";\n',
    '\nconst extra = import("./taskDraft");\n',
    '\nexport { extra } from "./unreviewed";\n',
  ]) {
    await writeFile(sourcePath, original + addition);
    await assert.rejects(run(directory), /Unreviewed module dependency|Unsupported module syntax/);
    await assert.rejects(stat(output), { code: "ENOENT" });
  }
  await writeFile(sourcePath, `${original}\nenum RequiresTransformation { First, Second }\n`);
  await assert.rejects(run(directory), /not supported in strip-only mode/);
  await assert.rejects(stat(output), { code: "ENOENT" });
});

test("line normalization preserves literal CRLF bytes and rejects multiline literals before changing assets", async t => {
  const directory = await isolated(t);
  const sourcePath = path.join(directory, sourceDirectory, "taskPayloadLanguage.ts");
  const original = await readFile(sourcePath, "utf8");
  await writeFile(sourcePath, `${original}\r\nexport const byteFixture = "原样\\r\\n한국어 😀\\t";\r\n`);
  await run(directory);
  const assetPath = path.join(directory, outputDirectory, "taskPayloadLanguage.js");
  const previous = await readFile(assetPath, "utf8");
  assert.doesNotMatch(previous, /\r|[ \t]+$/m);
  const api = await import(pathToFileURL(assetPath).href);
  assert.equal(api.byteFixture, "原样\r\n한국어 😀\t");
  for (const addition of ["\nconst extra = `first  \nsecond`;\n", '\nconst extra = "first\\\nsecond";\n']) {
    await writeFile(sourcePath, original + addition);
    await assert.rejects(run(directory), /Multiline literals require explicit review/);
    assert.equal(await readFile(assetPath, "utf8"), previous);
  }
});

test("generated Task-bound planner retains exact fixture pin, one-shot handoff and separate replacement", async () => {
  const { prepareTaskBoundContentSave } = await import(pathToFileURL(path.join(root, outputDirectory,
    "taskContentSave.js")).href);
  const fixture = JSON.parse(await read("engine/tests/fixtures/task-bound-content-save.json"));
  const attempt = await prepareTaskBoundContentSave(fixture.draft, fixture.baseline, fixture.guard, fixture.allocations);
  const step = attempt.next(fixture.guard);
  assert.deepEqual(step.body, fixture.publication_body);
  assert.throws(() => attempt.next(fixture.guard), { message: "taskSave.busy" });
  const receipt = artifactResponse({ body: { ...step.body, title: fixture.baseline.task.title } });
  assert.equal(attempt.confirm(clone(step), receipt, fixture.guard), false);
  assert.equal(attempt.confirm(step, receipt, fixture.guard), true);
  assert.equal(attempt.progress().taskConfirmed, false);
  const replacement = attempt.next(fixture.guard);
  assert.equal(replacement.kind, "replace");
  assert.equal(replacement.body.expected_revision, fixture.baseline.task.revision);
  assert.equal(replacement.body.manifest.title, fixture.draft.title);
  assert.equal(attempt.confirm(replacement, taskResponse(replacement, fixture.baseline), fixture.guard), true);
  assert.equal(attempt.progress().taskConfirmed, true);
  const stale = await prepareTaskBoundContentSave(fixture.draft, fixture.baseline, fixture.guard, fixture.allocations);
  assert.equal(stale.next({ ...fixture.guard, contextEpoch: fixture.guard.contextEpoch + 1 }), null);
  assert.equal(stale.progress().reason, "stale");
});
