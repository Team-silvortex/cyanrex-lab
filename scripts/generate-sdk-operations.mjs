import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { schemaToType } from "./generate-sdk-types.mjs";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const inputPath = path.join(projectRoot, "engine/openapi/openapi.json");
const outputPath = path.join(projectRoot, "sdk-js/src/generated/operations.ts");
const HTTP_METHODS = new Set(["delete", "get", "head", "options", "patch", "post", "put"]);
const SDK_EXEMPT_ACCESS = new Set(["runner-agent-bootstrap", "runner-agent-signed"]);

export function collectSdkOperations(document) {
  if (!document?.paths || typeof document.paths !== "object" || Array.isArray(document.paths)) {
    throw new Error("OpenAPI document does not define paths");
  }

  const operations = [];
  const operationIds = new Set();
  for (const [routePath, pathItem] of Object.entries(document.paths)) {
    if (!pathItem || typeof pathItem !== "object" || Array.isArray(pathItem)) continue;
    for (const [method, operation] of Object.entries(pathItem)) {
      if (!HTTP_METHODS.has(method)) continue;
      if (!operation || typeof operation !== "object" || Array.isArray(operation)) {
        throw new Error(`${method.toUpperCase()} ${routePath} has an invalid operation`);
      }

      const access = operation["x-cyanrex-access"];
      if (typeof access !== "string") {
        throw new Error(`${method.toUpperCase()} ${routePath} lacks x-cyanrex-access`);
      }
      if (SDK_EXEMPT_ACCESS.has(access)) continue;

      const operationId = operation.operationId;
      if (typeof operationId !== "string" || !operationId) {
        throw new Error(`${method.toUpperCase()} ${routePath} lacks operationId`);
      }
      if (operationIds.has(operationId)) throw new Error(`duplicate operationId ${operationId}`);
      operationIds.add(operationId);

      const parameters = mergeParameters(pathItem.parameters, operation.parameters);
      validatePathParameters(routePath, parameters);
      const { transport, responseSchema } = successfulResponse(operation, operationId);
      operations.push({
        access,
        inputSchema: operationInput(parameters, operation.requestBody, operationId),
        method: method.toUpperCase(),
        operationId,
        path: routePath,
        responseSchema,
        transport,
      });
    }
  }
  return operations.sort((left, right) => left.operationId.localeCompare(right.operationId));
}

export function renderSdkOperations(document) {
  const operations = collectSdkOperations(document);
  const accessTypes = [...new Set(operations.map(({ access }) => access))].sort();
  const methodTypes = [...new Set(operations.map(({ method }) => method))].sort();
  const lines = [
    "// This file is generated by scripts/generate-sdk-operations.mjs.",
    "// Do not edit it directly; update the OpenAPI operations and regenerate.",
    "",
    "import type { ApiDownload } from \"../types.js\";",
    "import type { OpenApiSchemas } from \"./openapi.js\";",
    "",
    "export interface OpenApiOperations {",
  ];

  for (const operation of operations) {
    lines.push(
      `  ${JSON.stringify(operation.operationId)}: {`,
      `    input: ${schemaToType(operation.inputSchema, 2)};`,
      `    response: ${responseType(operation)};`,
      "  };",
    );
  }

  lines.push(
    "}",
    "",
    "export type OpenApiOperationName = keyof OpenApiOperations;",
    "export type OpenApiOperationInput<Name extends OpenApiOperationName> = OpenApiOperations[Name][\"input\"];",
    "export type OpenApiOperationResponse<Name extends OpenApiOperationName> = OpenApiOperations[Name][\"response\"];",
    `export type OpenApiOperationAccess = ${accessTypes.map(JSON.stringify).join(" | ")};`,
    `export type OpenApiOperationMethod = ${methodTypes.map(JSON.stringify).join(" | ")};`,
    "export type OpenApiOperationTransport = \"download\" | \"json\" | \"websocket\";",
    "",
    "export interface OpenApiOperationDescriptor {",
    "  readonly method: OpenApiOperationMethod;",
    "  readonly path: string;",
    "  readonly access: OpenApiOperationAccess;",
    "  readonly transport: OpenApiOperationTransport;",
    "}",
    "",
    "export const openApiOperations = {",
  );
  for (const operation of operations) {
    const descriptor = {
      method: operation.method,
      path: operation.path,
      access: operation.access,
      transport: operation.transport,
    };
    lines.push(`  ${JSON.stringify(operation.operationId)}: ${JSON.stringify(descriptor)},`);
  }
  lines.push(
    "} as const satisfies Record<OpenApiOperationName, OpenApiOperationDescriptor>;",
    "",
  );
  return lines.join("\n");
}

function mergeParameters(pathParameters = [], operationParameters = []) {
  const merged = new Map();
  for (const parameter of [...pathParameters, ...operationParameters]) {
    if (!parameter || typeof parameter !== "object" || Array.isArray(parameter)) {
      throw new Error("OpenAPI operation has an invalid parameter");
    }
    if (parameter.$ref) throw new Error(`unsupported parameter reference ${parameter.$ref}`);
    if (typeof parameter.name !== "string" || typeof parameter.in !== "string" || !parameter.schema) {
      throw new Error("OpenAPI parameter requires name, in, and schema");
    }
    if (parameter.in !== "path" && parameter.in !== "query") {
      throw new Error(`unsupported ${parameter.in} parameter ${parameter.name}`);
    }
    merged.set(`${parameter.in}:${parameter.name}`, parameter);
  }
  return [...merged.values()];
}

function validatePathParameters(routePath, parameters) {
  const templateNames = [...routePath.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]).sort();
  const parameterNames = parameters
    .filter((parameter) => parameter.in === "path")
    .map((parameter) => parameter.name)
    .sort();
  if (JSON.stringify(templateNames) !== JSON.stringify(parameterNames)) {
    throw new Error(`${routePath} path template and parameters do not match`);
  }
  for (const parameter of parameters.filter((item) => item.in === "path")) {
    if (!parameter.required) throw new Error(`${routePath} path parameter ${parameter.name} must be required`);
  }
}

function operationInput(parameters, requestBody, operationId) {
  const properties = {};
  const required = [];
  for (const location of ["path", "query"]) {
    const selected = parameters.filter((parameter) => parameter.in === location);
    if (selected.length === 0) continue;
    properties[location] = parameterObject(selected);
    if (location === "path" || selected.some((parameter) => parameter.required)) required.push(location);
  }

  if (requestBody) {
    if (requestBody.$ref) throw new Error(`unsupported request body reference ${requestBody.$ref}`);
    const bodySchema = requestBody.content?.["application/json"]?.schema;
    if (!bodySchema) throw new Error(`${operationId} request body is not application/json`);
    properties.body = bodySchema;
    if (requestBody.required) required.push("body");
  }
  return { type: "object", properties, required, additionalProperties: false };
}

function parameterObject(parameters) {
  return {
    type: "object",
    properties: Object.fromEntries(parameters.map((parameter) => [parameter.name, parameter.schema])),
    required: parameters.filter((parameter) => parameter.required).map((parameter) => parameter.name),
    additionalProperties: false,
  };
}

function successfulResponse(operation, operationId) {
  if (operation.responses?.["101"]) {
    return { transport: "websocket", responseSchema: null };
  }
  const successStatus = Object.keys(operation.responses ?? {})
    .filter((status) => /^2\d\d$/.test(status))
    .sort()[0];
  if (!successStatus) throw new Error(`${operationId} lacks a successful response`);
  const content = operation.responses[successStatus]?.content ?? {};
  if (content["text/csv"]) return { transport: "download", responseSchema: null };
  const responseSchema = content["application/json"]?.schema;
  if (!responseSchema && Object.keys(content).length > 0) {
    throw new Error(`${operationId} successful response is not application/json`);
  }
  return { transport: "json", responseSchema: responseSchema ?? null };
}

function responseType(operation) {
  if (operation.transport === "download") return "ApiDownload";
  if (operation.transport === "websocket") return "string";
  return operation.responseSchema ? schemaToType(operation.responseSchema, 2) : "undefined";
}

export async function generateSdkOperations(options = {}) {
  const source = options.inputPath ?? inputPath;
  const destination = options.outputPath ?? outputPath;
  const document = JSON.parse(await readFile(source, "utf8"));
  const output = renderSdkOperations(document);
  const operations = collectSdkOperations(document).length;
  if (options.check) {
    const existing = await readFile(destination, "utf8").catch(() => "");
    if (existing !== output) {
      throw new Error("sdk-js/src/generated/operations.ts is stale; run node scripts/generate-sdk-operations.mjs");
    }
    return { operations, destination };
  }
  await mkdir(path.dirname(destination), { recursive: true });
  await writeFile(destination, output);
  return { operations, destination };
}

async function main() {
  const check = process.argv.includes("--check");
  const result = await generateSdkOperations({ check });
  const action = check ? "Generated SDK operations are current" : "Wrote generated SDK operations";
  console.log(`${action} (${result.operations} operations).`);
}

const invokedAsScript = process.argv[1]
  && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;
if (invokedAsScript) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
