import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { stripTypeScriptTypes } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const script = "scripts/generate-platform-task-save-assets.mjs";
const root = fileURLToPath(new URL("../", import.meta.url));
const sourceDirectory = "frontend/src/features/tasks";
const outputDirectory = "engine/src/bin/cyanrex-platform/session_ui/task-save";
// Changes to this graph require explicit review; source imports cannot extend it.
const names = Object.freeze(["taskContentSave", "taskSaveContract", "taskDraft", "taskPayloadLanguage"]);
const imports = new Map(names.map(name => [`./${name}`, `./${name}.js`]));

function render(name, bytes) {
  const sourcePath = `${sourceDirectory}/${name}.ts`;
  const source = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  // These reviewed sources have no multiline literals. Preserve their values by
  // refusing new multiline forms before normalizing generated line whitespace.
  if (/\\(?:\r\n?|\n)/.test(source)
    || [...source.matchAll(/`(?:\\[\s\S]|[^`\\])*`/g)].some(match => /[\r\n]/.test(match[0]))) {
    throw new Error(`Multiline literals require explicit review in ${sourcePath}`);
  }
  let content;
  try { content = stripTypeScriptTypes(source, { mode: "strip" }); }
  catch (error) {
    if (error.code === "ERR_NO_TYPESCRIPT") {
      throw new Error("Task-save asset generation requires Node built-in TypeScript support (Node 22.23+ or 24).");
    }
    throw error;
  }
  content = content.replace(/\r\n?/g, "\n").replace(/[ \t]+$/gm, "");
  // Deliberately support only the reviewed, single-line static sibling imports.
  // Apart from line whitespace, keep all strip output, including literal values.
  const declarations = /^([ \t]*import\b[^\r\n]*)$/gm;
  // The selected sources contain no other import token, even in comments/literals.
  // Reject unfamiliar placement rather than copying an unreviewed dependency.
  if (/\bimport\b|\bexport\s*(?:\*|{)/.test(content.replace(declarations, ""))) {
    throw new Error(`Unsupported module syntax in ${sourcePath}`);
  }
  content = content.replace(declarations, line => {
    const match = /^([ \t]*import[ \t]+[^;"'\r\n]+?[ \t]+from[ \t]+)(["'])([^"'\r\n]+)\2([ \t]*;[ \t]*)$/.exec(line);
    if (!match) throw new Error(`Unsupported module syntax in ${sourcePath}`);
    const replacement = imports.get(match[3]);
    if (!replacement) throw new Error(`Unreviewed module dependency in ${sourcePath}: ${match[3]}`);
    return `${match[1]}${match[2]}${replacement}${match[2]}${match[4]}`;
  });
  const header = [
    `// Generated by ${script}; do not edit directly.`,
    `// Source: ${sourcePath}`,
    `// Source SHA-256: ${createHash("sha256").update(bytes).digest("hex")}`,
    "",
  ].join("\n");
  const result = header + content;
  if (result.split("\n").length > 600) throw new Error(`Task-save asset exceeds 600 lines: ${name}.js`);
  return { relativePath: `${outputDirectory}/${name}.js`, content: result };
}

async function main() {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
    throw new Error(`Usage: node ${script} [--check]`);
  }
  // Render the whole fixed graph before creating or changing any output.
  const sources = await Promise.all(names.map(name => readFile(path.join(root, sourceDirectory, `${name}.ts`))));
  const assets = names.map((name, index) => render(name, sources[index]));
  if (args[0] === "--check") {
    const stale = [];
    for (const asset of assets) {
      let existing = null;
      try { existing = await readFile(path.join(root, asset.relativePath), "utf8"); }
      catch (error) { if (error.code !== "ENOENT") throw error; }
      if (existing !== asset.content) stale.push(asset.relativePath);
    }
    if (stale.length) throw new Error(`Task-save assets are stale: ${stale.join(", ")}. Run node ${script}.`);
    console.log(`${assets.length} Task-save assets synchronized.`);
    return;
  }
  await mkdir(path.join(root, outputDirectory), { recursive: true });
  for (const asset of assets) await writeFile(path.join(root, asset.relativePath), asset.content);
  console.log(`Generated ${assets.length} Task-save assets.`);
}

main().catch(error => { console.error(error.message); process.exitCode = 1; });
