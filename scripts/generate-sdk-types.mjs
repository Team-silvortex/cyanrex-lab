import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const inputPath = path.join(projectRoot, "engine/openapi/openapi.json");
const outputPath = path.join(projectRoot, "sdk-js/src/generated/openapi.ts");
const ANNOTATION_KEYWORDS = new Set([
  "$id", "$schema", "default", "deprecated", "description", "examples", "readOnly", "title", "writeOnly",
]);

export function schemaToType(schema, depth = 0) {
  if (!schema || typeof schema !== "object" || Array.isArray(schema)) {
    throw new TypeError("schema must be an object");
  }
  if (typeof schema.$ref === "string") return referenceType(schema.$ref);
  if (Object.hasOwn(schema, "const")) return literalType(schema.const);
  if (Array.isArray(schema.enum)) return schema.enum.map(literalType).join(" | ") || "never";
  if (Array.isArray(schema.anyOf)) return unionType(schema.anyOf, depth);
  if (Array.isArray(schema.oneOf)) return unionType(schema.oneOf, depth);
  if (Array.isArray(schema.allOf)) {
    return schema.allOf.map((item) => schemaToType(item, depth)).join(" & ") || "unknown";
  }

  let rendered;
  if (Array.isArray(schema.type)) {
    rendered = schema.type.map((type) => primitiveType(type)).join(" | ");
  } else {
    switch (schema.type) {
      case "string":
        rendered = "string";
        break;
      case "integer":
      case "number":
        rendered = "number";
        break;
      case "boolean":
        rendered = "boolean";
        break;
      case "null":
        rendered = "null";
        break;
      case "array":
        rendered = `Array<${schemaToType(schema.items ?? {}, depth)}>`;
        break;
      case "object":
        rendered = objectType(schema, depth);
        break;
      case undefined: {
        const unsupported = Object.keys(schema).filter((key) => !ANNOTATION_KEYWORDS.has(key));
        if (unsupported.length > 0) {
          throw new Error(`unsupported schema keywords: ${unsupported.sort().join(", ")}`);
        }
        rendered = "unknown";
        break;
      }
      default:
        throw new Error(`unsupported schema type ${schema.type}`);
    }
  }
  return schema.nullable && rendered !== "null" ? `${rendered} | null` : rendered;
}

export function renderSdkSchemaTypes(document) {
  const schemas = document?.components?.schemas;
  if (!schemas || typeof schemas !== "object" || Array.isArray(schemas)) {
    throw new Error("OpenAPI document does not define component schemas");
  }
  const lines = [
    "// This file is generated by scripts/generate-sdk-types.mjs.",
    "// Do not edit it directly; update the OpenAPI schemas and regenerate.",
    "",
    "export interface OpenApiSchemas {",
  ];
  for (const name of Object.keys(schemas).sort()) {
    lines.push(`  ${JSON.stringify(name)}: ${schemaToType(schemas[name], 1)};`);
  }
  lines.push(
    "}",
    "",
    "export type OpenApiSchemaName = keyof OpenApiSchemas;",
    "export type OpenApiSchema<Name extends OpenApiSchemaName> = OpenApiSchemas[Name];",
    "",
  );
  return lines.join("\n");
}

function objectType(schema, depth) {
  const properties = schema.properties ?? {};
  const entries = Object.entries(properties);
  if (entries.length === 0) {
    if (schema.additionalProperties === true) return "Record<string, unknown>";
    if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
      return `Record<string, ${schemaToType(schema.additionalProperties, depth)}>`;
    }
    return "Record<string, never>";
  }

  const required = new Set(schema.required ?? []);
  const indent = "  ".repeat(depth);
  const propertyIndent = "  ".repeat(depth + 1);
  const lines = ["{"];
  for (const [name, property] of entries) {
    const optional = required.has(name) ? "" : "?";
    lines.push(`${propertyIndent}${JSON.stringify(name)}${optional}: ${schemaToType(property, depth + 1)};`);
  }
  if (schema.additionalProperties === true) {
    lines.push(`${propertyIndent}[key: string]: unknown;`);
  }
  lines.push(`${indent}}`);
  return lines.join("\n");
}

function referenceType(reference) {
  const prefix = "#/components/schemas/";
  if (!reference.startsWith(prefix)) throw new Error(`unsupported schema reference ${reference}`);
  const name = reference.slice(prefix.length).replaceAll("~1", "/").replaceAll("~0", "~");
  return `OpenApiSchemas[${JSON.stringify(name)}]`;
}

function unionType(schemas, depth) {
  const members = schemas.map((item) => schemaToType(item, depth));
  return [...new Set(members)].join(" | ") || "never";
}

function primitiveType(type) {
  if (type === "integer" || type === "number") return "number";
  if (["string", "boolean", "null"].includes(type)) return type;
  throw new Error(`unsupported schema union type ${type}`);
}

function literalType(value) {
  if (value === null) return "null";
  if (["string", "number", "boolean"].includes(typeof value)) return JSON.stringify(value);
  throw new Error(`unsupported schema literal ${String(value)}`);
}

export async function generateSdkSchemaTypes(options = {}) {
  const source = options.inputPath ?? inputPath;
  const destination = options.outputPath ?? outputPath;
  const document = JSON.parse(await readFile(source, "utf8"));
  const output = renderSdkSchemaTypes(document);
  if (options.check) {
    const existing = await readFile(destination, "utf8").catch(() => "");
    if (existing !== output) {
      throw new Error("sdk-js/src/generated/openapi.ts is stale; run node scripts/generate-sdk-types.mjs");
    }
    return { schemas: Object.keys(document.components.schemas).length, destination };
  }
  await mkdir(path.dirname(destination), { recursive: true });
  await writeFile(destination, output);
  return { schemas: Object.keys(document.components.schemas).length, destination };
}

async function main() {
  const check = process.argv.includes("--check");
  const result = await generateSdkSchemaTypes({ check });
  const action = check ? "Generated SDK types are current" : "Wrote generated SDK types";
  console.log(`${action} (${result.schemas} schemas).`);
}

const invokedAsScript = process.argv[1]
  && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;
if (invokedAsScript) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
