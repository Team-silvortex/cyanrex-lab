use cyanrex_engine::{models::collaboration::*, services::file_transfer::*};
use sha2::{Digest, Sha256};
use std::io::{self, Read, Write};
#[cfg(unix)]
use std::os::unix::fs::PermissionsExt;

pub fn ids() -> (FileId, FileVersionId) {
    (
        FileId::try_from(uuid::Uuid::from_u128(1)).unwrap(),
        FileVersionId::try_from(uuid::Uuid::from_u128(2)).unwrap(),
    )
}

pub fn digest(bytes: &[u8]) -> Sha256Digest {
    format!("{:x}", Sha256::digest(bytes)).parse().unwrap()
}

pub fn small_manifest(bytes: &[u8]) -> FileTransferManifest {
    let (file_id, version_id) = ids();
    FileTransferManifest::new(
        super::scope(),
        file_id,
        version_id,
        "data.bin",
        bytes.len() as u64,
        if bytes.is_empty() {
            Vec::new()
        } else {
            vec![digest(bytes)]
        },
        digest(bytes),
    )
    .unwrap()
}

pub fn raw_manifest() -> serde_json::Value {
    let (file_id, version_id) = ids();
    serde_json::json!({
        "schema_version": 1,
        "workspace": super::scope(),
        "file_id": file_id,
        "version_id": version_id,
        "display_name": "data.bin",
        "byte_length": 11,
        "chunk_size": FILE_TRANSFER_CHUNK_BYTES,
        "chunk_sha256": [digest(b"inert bytes")],
        "sha256": digest(b"inert bytes")
    })
}

pub fn parse(value: &serde_json::Value) -> Result<FileTransferManifest, ContractError> {
    FileTransferManifest::parse_json(&serde_json::to_vec(value).unwrap())
}

pub fn pattern_byte(offset: u64) -> u8 {
    ((offset % 251 + (offset / FILE_TRANSFER_CHUNK_BYTES) * 73) % 251) as u8
}

pub struct PatternReader {
    pub start: u64,
    pub length: u64,
    pub consumed: u64,
    pub calls: usize,
    pub max_requested: usize,
    pub max_returned: usize,
}

impl PatternReader {
    pub fn new(start: u64, length: u64) -> Self {
        Self {
            start,
            length,
            consumed: 0,
            calls: 0,
            max_requested: 0,
            max_returned: FILE_TRANSFER_BUFFER_BYTES,
        }
    }
}

impl Read for PatternReader {
    fn read(&mut self, buffer: &mut [u8]) -> io::Result<usize> {
        assert!(
            buffer.len() <= FILE_TRANSFER_BUFFER_BYTES,
            "IO buffer exceeds 64 KiB"
        );
        self.calls += 1;
        self.max_requested = self.max_requested.max(buffer.len());
        let amount = ((self.length - self.consumed) as usize)
            .min(buffer.len())
            .min(self.max_returned);
        for (index, byte) in buffer[..amount].iter_mut().enumerate() {
            *byte = pattern_byte(self.start + self.consumed + index as u64);
        }
        self.consumed += amount as u64;
        Ok(amount)
    }
}

// Independent oracle: hashes generated bytes without invoking any production IO function.
pub fn pattern_manifest(length: u64) -> FileTransferManifest {
    let mut whole = Sha256::new();
    let mut chunks = Vec::new();
    let mut offset = 0;
    let mut buffer = [0u8; FILE_TRANSFER_BUFFER_BYTES];
    while offset < length {
        let mut chunk = Sha256::new();
        let end = (offset + FILE_TRANSFER_CHUNK_BYTES).min(length);
        while offset < end {
            let amount = ((end - offset) as usize).min(buffer.len());
            for (index, byte) in buffer[..amount].iter_mut().enumerate() {
                *byte = pattern_byte(offset + index as u64);
            }
            whole.update(&buffer[..amount]);
            chunk.update(&buffer[..amount]);
            offset += amount as u64;
        }
        chunks.push(format!("{:x}", chunk.finalize()).parse().unwrap());
    }
    let (file_id, version_id) = ids();
    FileTransferManifest::new(
        super::scope(),
        file_id,
        version_id,
        "data.bin",
        length,
        chunks,
        format!("{:x}", whole.finalize()).parse().unwrap(),
    )
    .unwrap()
}

pub struct PatternSink {
    pub start: u64,
    pub written: u64,
    pub calls: usize,
    pub max_write: usize,
}

impl PatternSink {
    pub fn new(start: u64, max_write: usize) -> Self {
        Self {
            start,
            written: 0,
            calls: 0,
            max_write,
        }
    }
}

impl Write for PatternSink {
    fn write(&mut self, buffer: &[u8]) -> io::Result<usize> {
        assert!(
            buffer.len() <= FILE_TRANSFER_BUFFER_BYTES,
            "copy buffer exceeds 64 KiB"
        );
        let amount = buffer.len().min(self.max_write);
        for (index, byte) in buffer[..amount].iter().enumerate() {
            assert_eq!(
                *byte,
                pattern_byte(self.start + self.written + index as u64)
            );
        }
        self.calls += 1;
        self.written += amount as u64;
        Ok(amount)
    }

    fn flush(&mut self) -> io::Result<()> {
        panic!("checked copy must not flush caller-owned sinks")
    }
}

pub struct FailReader {
    pub kind: io::ErrorKind,
    pub calls: usize,
}

impl Read for FailReader {
    fn read(&mut self, _: &mut [u8]) -> io::Result<usize> {
        self.calls += 1;
        if self.calls == 1 {
            Err(io::Error::from(self.kind))
        } else {
            Ok(0)
        }
    }
}

pub struct FailSink {
    pub kind: io::ErrorKind,
    pub calls: usize,
}

impl Write for FailSink {
    fn write(&mut self, _: &[u8]) -> io::Result<usize> {
        self.calls += 1;
        if self.calls == 1 {
            Err(io::Error::from(self.kind))
        } else {
            Ok(0)
        }
    }

    fn flush(&mut self) -> io::Result<()> {
        panic!("checked copy must not flush")
    }
}

pub fn assert_io(result: Result<(), FileTransferError>, kind: io::ErrorKind) {
    match result {
        Err(FileTransferError::Io(error)) => assert_eq!(error.kind(), kind),
        other => panic!("expected IO error {kind:?}, got {other:?}"),
    }
}

#[cfg(unix)]
pub struct FileFixture {
    pub directory: std::path::PathBuf,
    pub path: std::path::PathBuf,
    pub file: std::fs::File,
}

#[cfg(unix)]
impl FileFixture {
    pub fn new(length: u64) -> Self {
        let directory =
            std::env::temp_dir().join(format!("cyanrex-file-core-{}", uuid::Uuid::new_v4()));
        std::fs::create_dir(&directory).unwrap();
        std::fs::set_permissions(&directory, std::fs::Permissions::from_mode(0o700)).unwrap();
        let path = directory.join("data.bin");
        let mut file = std::fs::OpenOptions::new()
            .read(true)
            .write(true)
            .create_new(true)
            .open(&path)
            .unwrap();
        let mut reader = PatternReader::new(0, length);
        std::io::copy(&mut reader, &mut file).unwrap();
        std::io::Seek::rewind(&mut file).unwrap();
        Self {
            directory,
            path,
            file,
        }
    }
}

#[cfg(unix)]
impl Drop for FileFixture {
    fn drop(&mut self) {
        std::fs::remove_dir_all(&self.directory).expect("remove only this exclusive test fixture");
    }
}
