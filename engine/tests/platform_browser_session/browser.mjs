// Real browser only. No route.fulfill, injected platform Cookie or mocked Session response.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import * as fs from "node:fs/promises";
import { existsSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { join, isAbsolute } from "node:path";
import { pathToFileURL } from "node:url";
import { createInterface } from "node:readline";

const lines = createInterface({ input: process.stdin, terminal: false });
const input = lines[Symbol.asyncIterator]();
const read = async () => {
  const next = await input.next();
  assert.ok(!next.done && next.value.length < 4096, "bounded private fixture IPC required");
  return JSON.parse(next.value);
};
const emit = value => process.stdout.write(`${JSON.stringify(value)}\n`);
const advance = async () => assert.deepEqual(await read(), { continue: true });
const execute = promisify(execFile);
let context, testDirectory, stage = "browser-startup";

async function launch(chromium, dataDirectory) {
  return chromium.launchPersistentContext(join(testDirectory, "profile"), {
    executablePath: process.env.CYANREX_CHROMIUM_PATH,
    headless: true,
    ignoreHTTPSErrors: false,
    viewport: { width: 1000, height: 850 },
    env: { ...process.env, XDG_DATA_HOME: dataDirectory,
      XDG_CONFIG_HOME: join(testDirectory, "config"), XDG_CACHE_HOME: join(testDirectory, "cache") },
  });
}

async function prepare(config) {
  for (const key of ["CYANREX_PLAYWRIGHT_MODULE", "CYANREX_CHROMIUM_PATH"]) {
    assert.ok(process.env[key] && isAbsolute(process.env[key]), "explicit browser dependencies required");
  }
  if (config.tls) assert.ok(!existsSync(join(homedir(), ".pki/nssdb")),
    "legacy user NSS takes precedence over private XDG trust; TLS fixture is blocked, never bypassed");
  const { chromium } = await import(pathToFileURL(process.env.CYANREX_PLAYWRIGHT_MODULE).href);
  testDirectory = await fs.mkdtemp(join(tmpdir(), "cyanrex-platform-browser-"));
  await fs.chmod(testDirectory, 0o700);
  const dataDirectory = join(testDirectory, "data");
  await fs.mkdir(dataDirectory, { recursive: true, mode: 0o700 });
  if (config.tls) {
    const nss = join(dataDirectory, "pki/nssdb");
    await fs.mkdir(nss, { recursive: true, mode: 0o700 });
    await execute("certutil", ["-N", "--empty-password", "-d", `sql:${nss}`], { timeout: 10000 });
    context = await launch(chromium, dataDirectory);
    const page = context.pages()[0];
    let rejected = false;
    try { await page.goto(`${config.origin}/platform/`, { timeout: 10000 }); }
    catch (error) { rejected = String(error.message).includes("ERR_CERT_AUTHORITY_INVALID"); }
    assert.ok(rejected, "empty private CA store must produce a certificate authority failure, not a timeout");
    await context.close(); context = undefined;
    emit({ phase: "ca_rejected" }); await advance();
    // This directory is generated by this process. No system or real-account trust is changed.
    await execute("certutil", ["-A", "-d", `sql:${nss}`, "-n", "Cyanrex disposable fixture CA", "-t", "C,,", "-i", config.ca_file], { timeout: 10000 });
  }
  context = await launch(chromium, dataDirectory);
  return context.pages()[0];
}

async function run(config) {
  const page = await prepare(config);
  if (config.smoke) {
    await page.goto("data:text/html,<title>Private browser smoke</title><p>ready</p>");
    assert.equal(await page.title(), "Private browser smoke");
    emit({ phase: "smoke_complete" }); return;
  }
  const origin = new URL(config.origin).origin;
  const paths = new Set(["/platform/", "/platform/ui/app.js", "/platform/ui/labels.js", "/platform/ui/style.css", "/platform/ui/tasks.js", "/platform/ui/task-contract.js", "/platform/ui/task-edit.js", "/favicon.ico",
    "/platform/v1/session/login", "/platform/v1/session", "/platform/v1/session/logout"]);
  const calls = [], checks = [], errors = [];
  page.on("pageerror", () => errors.push("unexpected page runtime error"));
  page.on("request", request => {
    const url = new URL(request.url());
    calls.push({ method: request.method(), path: url.pathname });
    checks.push((async () => {
      assert.equal(url.origin, origin, "no external or teaching request is allowed");
      assert.ok(paths.has(url.pathname) && !url.search && !url.username && !url.password,
        "fixed credential-free same-origin URLs required");
      if (url.pathname.startsWith("/platform/v1/")) {
        const headers = await request.allHeaders();
        assert.equal(headers["x-cyanrex-platform-request"], "1");
        if (request.method() === "POST") assert.equal(headers.origin, origin,
          "the real browser must generate the exact POST Origin");
      } else assert.equal(request.method(), "GET");
    })());
  });
  const count = path => calls.filter(call => call.path === path).length;
  const flush = async () => { await Promise.all(checks); assert.deepEqual(errors, []); };
  const state = async expected => {
    stage = `waiting-for-${expected}`;
    await page.waitForFunction(value => document.querySelector("#status")?.dataset.state === value
      && document.body.dataset.busy === "false", expected, { timeout: 10000 });
    await flush();
  };
  const cookie = async () => {
    stage = "private-cookie-policy";
    const cookies = await context.cookies(`${origin}/platform/v1/session`);
    const selected = cookies.filter(value => value.name === "cyanrex_platform_session");
    assert.equal(selected.length, 1, "one naturally issued platform Cookie required");
    const value = selected[0];
    assert.ok(/^[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$/.test(value.value), "canonical private token required");
    assert.equal(value.domain, new URL(origin).hostname);
    assert.equal(value.path, "/platform/v1"); assert.equal(value.httpOnly, true);
    assert.equal(value.secure, config.tls); assert.equal(value.sameSite, "Strict");
    assert.equal(value.expires, -1);
    return value;
  };
  const safePage = async token => {
    stage = "credential-free-page-and-storage";
    assert.ok(!(await page.evaluate(() => document.cookie)).includes("cyanrex_platform_session"));
    assert.ok(!(await page.locator("body").innerText()).includes(token));
    const stored = await page.evaluate(() => [...Object.values(localStorage), ...Object.values(sessionStorage)]);
    assert.ok(stored.every(value => ![token, config.password, config.otp].some(secret => value.includes(secret))), "secrets must not enter Web Storage");
    assert.equal(page.frames().length, 1); assert.equal(context.pages().length, 1);
  };
  await page.goto(`${origin}/platform/`);
  await state("unauthenticated"); assert.equal(count("/platform/v1/session"), 1);
  assert.ok(!Object.hasOwn(config, "otp"), "startup configuration must not contain a prematurely sampled OTP");
  emit({ phase: "ready_login" });
  const fresh = await read();
  assert.deepEqual(Object.keys(fresh), ["otp"], "one private OTP handoff required");
  assert.ok(typeof fresh.otp === "string" && /^[0-9]{6}$/.test(fresh.otp), "one fresh synthetic OTP required");
  config.otp = fresh.otp;
  await page.locator("#username").fill(config.username);
  await page.locator("#password").fill(config.password);
  await page.locator("#otp").fill(config.otp);
  await page.locator("#login").click();
  await state("active");
  assert.equal(count("/platform/v1/session/login"), 1);
  assert.equal(count("/platform/v1/session"), 2, "one independent GET must verify the browser received the issued Cookie");
  assert.equal(await page.locator("#password").inputValue(), ""); assert.equal(await page.locator("#otp").inputValue(), "");
  const issued = await cookie();
  await safePage(issued.value);
  await page.reload(); await state("active");
  assert.equal(count("/platform/v1/session"), 3, "reload must verify the real browser Cookie again");
  const beforeLocale = calls.length;
  stage = "locale-without-authentication";
  await page.locator("#locale").selectOption("zh-CN"); await page.locator("#locale").selectOption("en");
  await flush(); assert.equal(calls.length, beforeLocale, "locale switching must not dispatch authentication");
  await safePage(issued.value);
  const digest = createHash("sha256").update(issued.value).digest("hex");
  emit({ phase: "authenticated", digest }); await advance();
  stage = "logout-cancellation-and-focus";
  await page.locator("#logout").click(); await page.locator("#logout-dialog").waitFor({ state: "visible" });
  assert.equal(await page.evaluate(() => document.activeElement?.id), "cancel-logout");
  await page.locator("#cancel-logout").click(); await page.locator("#logout-dialog").waitFor({ state: "hidden" });
  await state("active"); assert.equal(count("/platform/v1/session/logout"), 0);
  emit({ phase: "cancelled" }); await advance();
  const confirm = async () => { await page.locator("#logout").click(); await page.locator("#confirm-logout").click(); };
  await confirm();
  if (config.uncertain_logout) {
    await state("unknown"); assert.equal(count("/platform/v1/session/logout"), 1);
    assert.ok((await cookie()).value === issued.value, "unconfirmed logout must not clear the browser Cookie");
    emit({ phase: "uncertain_logout" }); await advance();
    await page.locator("#check-session").click(); await state("active");
    await confirm();
  }
  await state("unauthenticated");
  assert.equal(count("/platform/v1/session/logout"), config.uncertain_logout ? 2 : 1,
    "only explicit confirmations may dispatch logout; never automatic retries");
  assert.equal((await context.cookies(`${origin}/platform/v1/session`)).filter(c => c.name === "cyanrex_platform_session").length, 0);
  await page.locator("#check-session").click(); await state("unauthenticated");
  assert.equal(count("/platform/v1/session/login"), 1); await flush();
  emit({ phase: "logged_out" }); await advance();
  await context.close(); context = undefined;
  emit({ phase: "complete" });
}

try { await run(await read()); }
catch { emit({ phase: "failure", stage }); process.stderr.write("platform browser fixture failed\n"); process.exitCode = 1; }
finally {
  await context?.close().catch(() => {});
  lines.close();
  if (testDirectory) await fs.rm(testDirectory, { recursive: true, force: true });
}
